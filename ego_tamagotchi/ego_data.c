const EgoQuest* ego_quest(uint8_t pool_index) {
    return &k_pool[pool_index < EGO_POOL_COUNT ? pool_index : 0];
}

/* Причины ухода после возврата: без драмы, только две. Каждая со штрафом (налог на анализ). */
const char* ego_cause_label(uint8_t index) {
    static const char* const labels[EGO_CAUSE_COUNT] = {"Анализ", "Выход из EGO"};
    return labels[index < EGO_CAUSE_COUNT ? index : 0];
}

/* Ранги в круге: E D C B A S. Буква пишется латиницей (шрифт приложения её знает). */
const char* ego_band_letter(uint8_t band) {
    static const char* const letters[EGO_BANDS] = {"E", "D", "C", "B", "A", "S"};
    return letters[band < EGO_BANDS ? band : 0];
}

const char* ego_band_name(uint8_t band) {
    static const char* const names[EGO_BANDS] = {
        "КРИТИЧЕСКИЙ",
        "СЛАБЫЙ",
        "СРЕДНИЙ",
        "СТАБИЛЬНЫЙ",
        "ВЫСОКИЙ",
        "ВЫСШИЙ",
    };
    return names[band < EGO_BANDS ? band : 0];
}

/* Римские цифры для степени ранга S и номера круга. */
const char* ego_roman(uint8_t n) {
    static const char* const roman[EGO_CIRCLES + 1] = {
        "", "I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI"};
    return n <= EGO_CIRCLES ? roman[n] : "";
}

const char* ego_pillar_name(uint8_t pillar) {
    static const char* const names[EGO_PILLARS] = {"ТЕЛО", "ДЕЛА", "ДЕНЬГИ", "ПОЗИЦИЯ", "ТИШИНА"};
    return names[pillar < EGO_PILLARS ? pillar : 0];
}
